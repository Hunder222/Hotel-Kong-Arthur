SET client_encoding = 'UTF8';

CREATE TABLE IF NOT EXISTS room_types (
    id          SMALLINT     PRIMARY KEY CHECK (id BETWEEN 1 AND 8),
    name        VARCHAR(40)  NOT NULL UNIQUE,
    name_da     VARCHAR(60)  NOT NULL,
    room_count  SMALLINT     NOT NULL CHECK (room_count > 0),
    max_guests  SMALLINT     NOT NULL CHECK (max_guests BETWEEN 1 AND 4)
);

CREATE TABLE IF NOT EXISTS room_type_rates (
    room_type_id          SMALLINT      NOT NULL REFERENCES room_types (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    season                VARCHAR(10)   NOT NULL CHECK (season IN ('low', 'mid', 'high')),
    min_nightly_dkk       NUMERIC(10,2) NOT NULL CHECK (min_nightly_dkk > 0),
    max_nightly_dkk       NUMERIC(10,2) NOT NULL CHECK (max_nightly_dkk >= min_nightly_dkk),
    standard_nightly_dkk  NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (room_type_id, season),
    CONSTRAINT chk_rates_standard_between
        CHECK (standard_nightly_dkk BETWEEN min_nightly_dkk AND max_nightly_dkk)
);

CREATE TABLE IF NOT EXISTS bookings (
    id             INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(100)  NOT NULL,
    family_name    VARCHAR(100)  NOT NULL,
    country        VARCHAR(100)  NOT NULL,
    room_type_id   SMALLINT      NOT NULL REFERENCES room_types (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    check_in_date  DATE          NOT NULL,
    days_rented    SMALLINT      NOT NULL CHECK (days_rented BETWEEN 1 AND 365),
    price_dkk      NUMERIC(10,2) NOT NULL CHECK (price_dkk > 0),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_bookings_check_in_date ON bookings (check_in_date);
CREATE INDEX IF NOT EXISTS ix_bookings_room_type_id ON bookings (room_type_id);

CREATE TABLE IF NOT EXISTS reviews (
    id            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    INTEGER      REFERENCES bookings (id) ON DELETE SET NULL ON UPDATE CASCADE,
    room_type_id  SMALLINT     NOT NULL REFERENCES room_types (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    stay_date     DATE         NOT NULL,
    rating        SMALLINT     NOT NULL CHECK (rating BETWEEN 1 AND 5),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_reviews_stay_date ON reviews (stay_date);
CREATE INDEX IF NOT EXISTS ix_reviews_room_type_id ON reviews (room_type_id);
CREATE INDEX IF NOT EXISTS ix_reviews_booking_id ON reviews (booking_id);

CREATE TABLE IF NOT EXISTS bar_drink_sales (
    id              INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_year      SMALLINT      NOT NULL CHECK (sales_year BETWEEN 2000 AND 2100),
    drink_name      VARCHAR(100)  NOT NULL,
    category        VARCHAR(20)   NOT NULL CHECK (category IN ('Cocktail', 'Coffee')),
    unit_price_dkk  NUMERIC(10,2) NOT NULL CHECK (unit_price_dkk > 0),
    units_sold      INTEGER       NOT NULL CHECK (units_sold >= 0),
    UNIQUE (sales_year, drink_name)
);
